    private static readonly object _sync = new();
    private static string _language = SettingsStore.ReadValue("language") ?? SystemLanguage;

    /// <summary>当前选择（含 "system"）。</summary>
    public static string SelectedLanguage
    {
        get { lock (_sync) return _language; }
    }

    /// <summary>实际生效语言（"system" 解析为系统 UI 语言）。</summary>
    public static string EffectiveLanguage
    {
        get
        {
            lock (_sync)
            {
                if (_language == English) return English;
                if (_language == Chinese) return Chinese;
                return CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("zh", StringComparison.OrdinalIgnoreCase)
                    ? Chinese
                    : English;
            }
        }
    }

    public static void SetLanguage(string language)
    {
        string normalized = language is SystemLanguage or Chinese or English ? language : SystemLanguage;
        lock (_sync)
        {
            if (_language == normalized) return;
            _language = normalized;
        }
        SettingsStore.WriteValue("language", normalized);
        LanguageChanged?.Invoke(null, EventArgs.Empty);
    }

    /// <summary>翻译；缺失键回退中文，再回退键名本身。</summary>
    public static string T(string key, params object[] args)
    {
        string text;
        lock (_sync)
        {
            Dictionary<string, string> dict = EffectiveLanguage == English ? EnglishStrings : ChineseStrings;
            if (!dict.TryGetValue(key, out text) && !ChineseStrings.TryGetValue(key, out text)) text = key;
        }
        return args.Length == 0 ? text : string.Format(CultureInfo.CurrentCulture, text, args);
    }
